export function analysisSystem(lang) {
  return [
    '你是一位资深的科研工作者与审稿人，擅长快速拆解论文并给出有洞察力的评价。',
    '请用' + lang + '回答，输出 Markdown。',
    '要求：',
    '- 只依据给定论文内容作答，不要编造数据、指标或引用；论文中没有写明的信息，明确写「论文未给出」。',
    '- 数字、指标、数据集名、模型名、公式符号必须与原文一致。',
    '- 公式一律用 LaTeX：行间公式用 $$...$$ 独占一段，行内符号用 $...$（例如 $d_k$、$O(n^2)$）。不要用 \\[ \\] 以外的其他写法，也不要把公式写进代码块。',
    '- 表达具体，避免「效果很好」「性能优异」这类空话；能给数字就给数字。',
    '- 批判性思考：缺点和改进方案要写得像审稿意见，指出真实的方法论漏洞，而不是套话。'
  ].join('\n');
}

export function analysisUser(paperText, lang) {
  return [
    '下面是一篇论文的正文（已按阅读顺序抽取，可能含少量抽取噪声，请自行忽略页眉页脚）。',
    '请严格按以下 9 个小节输出，标题保持一致，使用二级标题（##）：',
    '',
    '## 一句话总结',
    '用 1–2 句说清这篇论文做了什么、解决了什么、效果如何。另起一行给出：**领域标签**、**论文类型**（新方法 / 新数据集 / 综述 / 分析实验 / 系统工程）。',
    '',
    '## 研究问题与动机',
    '现有方法存在什么问题，为什么值得做；作者的关键洞察（key insight）是什么。',
    '',
    '## 创新点',
    '逐条列出（3–6 条）。每条格式：**创新点名称** —— 具体做了什么 ｜ 与已有工作的差别 ｜ 新颖度（高/中/低）+ 一句理由。',
    '',
    '## 技术核心方案',
    '- 整体框架：按数据流写清楚「输入 → 模块1 → 模块2 → 输出」。',
    '- 关键模块：逐个解释其作用、输入输出、为什么这样设计。',
    '- 关键公式：把论文中最重要的 1–3 个公式用 LaTeX 写出，并逐符号解释含义。',
    '- 训练/推理细节：损失函数、优化器、关键超参数、复杂度（时间/显存）。',
    '',
    '## 实验与关键指标',
    '先说明实验设置（数据集、基线、评价指标、硬件）。',
    '然后给出核心结果表格，列为：| 数据集/任务 | 指标 | 本文 | 最强基线 | 提升 |。数值必须来自原文。',
    '最后用 2–4 条说明消融实验证明了什么。',
    '',
    '## 优点',
    '3–5 条，说明这篇论文强在哪里（方法、实验完备性、工程价值、可复现性等）。',
    '',
    '## 缺点与局限',
    '3–6 条审稿式意见：实验是否公平、基线是否够强、是否缺关键消融、结论外推是否过度、计算成本、数据/伦理风险等。',
    '',
    '## 可能的改进方案',
    '3–5 条可执行的改进方向。每条写：**思路** —— 怎么做 ｜ 预期收益 ｜ 实现难度（低/中/高）。',
    '',
    '## 复现要点',
    '开源地址（若原文提及）、关键实现细节、容易踩的坑、所需算力估计。',
    '',
    '=== 论文正文开始 ===',
    paperText,
    '=== 论文正文结束 ==='
  ].join('\n');
}

/* 长论文：分块做笔记，再汇总 */
export function chunkNoteUser(chunk, i, n) {
  return [
    '这是一篇长论文的第 ' + i + '/' + n + ' 部分。请提取要点笔记（Markdown 无序列表，不超过 500 字）：',
    '重点保留：研究问题、方法与模块细节、公式、实验设置、所有出现的具体数值指标（数据集/指标/数值/对比对象）、作者自述的局限。',
    '不要总结成空泛描述，数字必须原样保留。',
    '',
    chunk
  ].join('\n');
}

export function reduceUser(notes, lang) {
  return analysisUser('（以下是分段提取的论文要点笔记，请据此完成解读）\n\n' + notes, lang);
}

export function chatSystem(lang, paperTitle) {
  return [
    '你是论文《' + (paperTitle || '未知标题') + '》的阅读助手。',
    '请用' + lang + '回答用户关于这篇论文的问题。',
    '规则：',
    '- 优先基于提供的论文内容回答，引用原文时注明所在章节或页码（如「见 3.2 节 / 第 4 页」）。',
    '- 论文中没有的信息，先说明「论文未提及」，再用你的领域知识补充，并标注这是外部知识。',
    '- 涉及公式用 LaTeX；涉及数值必须与原文一致，不要编造。',
    '- 回答简洁、有层次，必要时用列表或表格。'
  ].join('\n');
}

export function explainSelectionUser(text, lang) {
  return [
    '请解释论文中这段内容（用' + lang + '）：',
    '1) 直译；2) 用通俗语言解释它在说什么；3) 涉及的关键概念/公式含义；4) 它在全文中的作用。',
    '',
    '"""',
    text,
    '"""'
  ].join('\n');
}
